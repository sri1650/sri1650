from pathlib import Path
import json
from servo_lab.parameters import load_config


def test_generated_cpp_config_contains_expected_values():
    root=Path(__file__).resolve().parents[1]
    text=(root/"cpp/include/servo/generated_assumptions.hpp").read_text()
    cfg=load_config()
    assert "Generated by tools/generate_cpp_config.py" in text
    assert repr(cfg.mechanics.pulley_radius_m) in text
    assert repr(cfg.motor.dc_bus_v) in text
    assert repr(cfg.control.tick_s) in text
    assert "kNominalMoveDurationS" in text
