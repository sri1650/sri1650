"""Generate C++ aggregate from the single source-of-truth JSON configuration."""
from __future__ import annotations
from pathlib import Path
import json
import math

ROOT=Path(__file__).resolve().parents[1]


def generate():
    cfg=json.loads((ROOT/"config/assumed_axis.json").read_text())
    m=cfg["mechanics"]
    e=cfg["motor"]
    c=cfg["control"]
    s=cfg["supervision"]
    data=[c["tick_s"],int(c["position_loop_divisor"]),int(c["velocity_loop_divisor"]),
          c["position_kp_per_s"],c["velocity_kp_a_per_rad_s"],c["velocity_ki_a_per_rad"],
          c["current_kp_v_per_a"],c["current_ki_v_per_a_s"],c["current_limit_a"],c["max_speed_m_s"],
          e["dc_bus_v"],e["winding_resistance_ohm"],e["back_emf_constant_v_per_rad_s"],
          e["torque_constant_nm_per_a"],m["moving_mass_kg"],m["coulomb_friction_coefficient"],
          m["gravity_m_s2"],m["friction_smoothing_velocity_m_s"],m["gear_ratio_motor_to_output"],
          m["pulley_radius_m"],m["transmission_efficiency"],m["travel_min_m"],m["travel_max_m"],s["soft_limit_margin_m"]]
    d=abs(c["target_position_m"]-m["travel_min_m"])
    duration=max(0.1,1.875*d/c["max_speed_m_s"],math.sqrt((10*math.sqrt(3)/3)*d/c["max_acceleration_m_s2"]),(60*d/c["max_jerk_m_s3"])**(1/3))
    content = "// Generated by tools/generate_cpp_config.py; do not hand edit.\n#pragma once\n#include \"servo/control.hpp\"\nnamespace servo {\ninline constexpr AxisConfig kAssumedConfig{\n" + ",\n".join("    "+repr(v) for v in data) + "\n};\ninline constexpr double kNominalMoveDurationS = "+repr(duration)+";\n}\n"
    dest=ROOT/"cpp/include/servo/generated_assumptions.hpp"
    dest.write_text(content)
    return dest

if __name__=="__main__": print(generate())
