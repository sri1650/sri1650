#!/usr/bin/env python3
"""Generate a self-contained offline interactive SIL results viewer. No network required."""
from __future__ import annotations
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"src"))
from servo_lab.runner import run_simulation,Scenario


def generate(path:Path=ROOT/"outputs/servo_control_dashboard.html") ->Path:
    specs=[Scenario(),Scenario("6 N load disturbance",disturbance_force_n=6),
           Scenario("Encoder invalid",inject_fault="encoder_invalid"),
           Scenario("Heartbeat timeout",inject_fault="heartbeat_loss"),
           Scenario("Emergency-stop input",inject_fault="emergency_stop")]
    runs={}
    for spec in specs:
        res=run_simulation(scenario=spec)
        # Subsample only for display; raw full-rate CSV is retained separately.
        runs[spec.name]={"summary":res.summary(),"series":[r for i,r in enumerate(res.trajectory) if i%5==0 or i==len(res.trajectory)-1]}
    payload=json.dumps(runs,separators=(",",":"),allow_nan=False)
    template='''<!doctype html>
<html lang="en"><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>Servo Motion Control — SIL Evidence</title>
<style>
:root {font-family:ui-monospace,Menlo,Consolas,monospace;color-scheme:dark;background:#0c1220;color:#e2e8f0}
body{margin:0 auto;padding:16px;max-width:1150px}
header{padding:16px;border-bottom:1px solid #374151;margin-bottom:18px}
h1{font-family:system-ui;margin:.25em 0;font-weight:650;font-size:1.6em}
main{display:grid;gap:14px;grid-template-columns:1.35fr 1fr}
.card{background:#172233;border:1px solid #344052;border-radius:12px;padding:15px}
small,.muted{color:#a0aec0} h2{font-size:1em;margin:0 0 12px} select, input{width:100%;padding:9px;box-sizing:border-box;background:#0c1220;color:#e2e8f0;border:1px solid #475569;border-radius:8px}
svg{width:100%;height:auto;display:block;background:#0c1728;border-radius:8px}
.metrics{display:grid;grid-template-columns:repeat(2,1fr);gap:8px}
.metric{padding:10px;background:#0c1728;border-radius:8px}.metric strong{display:block;font-size:1.15rem;margin-top:6px}
.legend{font-size:12px;margin:6px 0 0} .warn{background:#352a19;border:1px solid #88692d;color:#f2d4a1;padding:10px;border-radius:8px}
@media(max-width:760px){main{grid-template-columns:1fr}}
</style></head><body>
<header><small>PROJECT 4 / MECHATRONICS ENGINEERING SOFTWARE</small><h1>Servo Motion Control · Software-in-the-loop</h1><div class="muted">Cascaded P/PI/PI control · assumed 8 kg axis · 1 kHz software model · no connected hardware</div></header>
<div class="warn"><b>Evidence boundary:</b> Every trajectory shown here is generated by a simplified assumed motor and load model. The fault plots are not validated stopping distances or safety-rated control.</div>
<main>
<section class="card"><h2>Choose scenario</h2><select id="scenario"></select>
<h2 style="margin-top:17px">Axis position (mm)</h2><svg id="position" viewBox="0 0 620 250" role="img" aria-label="position and reference chart"></svg>
<div class="legend">Solid line: simulated position · Dashed line: reference</div>
<h2 style="margin-top:18px">Winding current (A)</h2><svg id="current" viewBox="0 0 620 205" role="img" aria-label="motor current chart"></svg></section>
<aside class="card"><h2>Time cursor</h2><input type="range" id="cursor" min="0" value="0" step="1"/><div id="time" class="muted" style="margin:12px 0"></div>
<div class="metrics"><div class="metric">Position<strong id="p"></strong></div><div class="metric">Reference<strong id="r"></strong></div>
<div class="metric">Current<strong id="i"></strong></div><div class="metric">Voltage<strong id="v"></strong></div>
<div class="metric">Drive mode<strong id="mode"></strong></div><div class="metric">Fault detection<strong id="fault"></strong></div></div>
<h2 style="margin-top:20px">Run outcome</h2><div id="summary" class="muted"></div></aside>
</main><p class="muted">The full-rate data, source code, test suite and assumptions are in the project archive. No fieldbus or real embedded target has been tested.</p>
<script>
const raw=__JSON_DATA__;
const select=document.getElementById('scenario');
for(const name of Object.keys(raw)){const o=document.createElement('option');o.textContent=name;o.value=name;select.appendChild(o)}
const slider=document.getElementById('cursor');
function text(id,s){document.getElementById(id).textContent=s}
function plot(id,rows,key,extraKey,unit){
 const svg=document.getElementById(id),w=620,h=id==='position'?250:205;
 const x0=48,y0=12,x1=w-16,y1=h-35;
 const arr=rows.map(r=>r[key]*unit);
 if(extraKey) arr.push(...rows.map(r=>r[extraKey]*unit));
 let mn=Math.min(...arr),mx=Math.max(...arr);if(mx-mn<.001){mx+=.5;mn-=.5}else{const pad=(mx-mn)*.12;mx+=pad;mn-=pad}
 const n=rows.length;
 const xx=i=>x0+i*(x1-x0)/Math.max(1,n-1);
 const yy=v=>y1-(v-mn)/(mx-mn)*(y1-y0);
 const path=field=>rows.map((r,i)=>(i?'L':'M')+xx(i).toFixed(2)+' '+yy(r[field]*unit).toFixed(2)).join(' ');
 const xticks=Array.from({length:6},(_,i)=>{const idx=Math.round(i*(n-1)/5);return `<text x="${xx(idx)}" y="${h-11}" text-anchor="middle" fill="#9aa9bc" font-size="12">${rows[idx].t_s.toFixed(1)}s</text>`}).join('');
 const ylabels=[0,.5,1].map(f=>{const v=mn+f*(mx-mn);return `<text x="${x0-6}" y="${yy(v)+4}" text-anchor="end" fill="#9aa9bc" font-size="12">${v.toFixed(1)}</text>`}).join('');
 const secondary=extraKey?`<path d="${path(extraKey)}" fill="none" stroke="#a5b4fc" stroke-dasharray="5 4" stroke-width="2"/>`:'';
 const cursorx=xx(Math.min(n-1,+slider.value));
 svg.innerHTML=`<line x1="${x0}" y1="${y0}" x2="${x0}" y2="${y1}" stroke="#768799"/><line x1="${x0}" y1="${y1}" x2="${x1}" y2="${y1}" stroke="#768799"/>${xticks}${ylabels}<path d="${path(key)}" fill="none" stroke="#70d0bc" stroke-width="2"/>${secondary}<line x1="${cursorx}" x2="${cursorx}" y1="${y0}" y2="${y1}" stroke="#fff" stroke-width="1" stroke-opacity="0.5"/>`;
}
function render(){
 const obj=raw[select.value],rows=obj.series,r=rows[Math.min(rows.length-1,+slider.value)],s=obj.summary;
 slider.max=rows.length-1;
 text('time',r.t_s.toFixed(3)+' s / '+rows[rows.length-1].t_s.toFixed(3)+' s');
 text('p',(r.position_m*1000).toFixed(3)+' mm');text('r',(r.reference_m*1000).toFixed(3)+' mm');
 text('i',r.current_a.toFixed(3)+' A');text('v',r.command_voltage_v.toFixed(2)+' V');
 text('mode',r.mode);text('fault',s.first_fault_s==null?'None':s.first_fault_s.toFixed(3)+' s');
 text('summary','Final error '+(s.final_error_m*1000).toFixed(3)+' mm; peak current '+s.peak_current_a.toFixed(3)+' A; post-fault additional travel '+(s.post_fault_travel_m==null?'n/a':(s.post_fault_travel_m*1000).toFixed(2)+' mm'));
 plot('position',rows,'position_m','reference_m',1000);plot('current',rows,'current_a',null,1);
}
select.onchange=()=>{slider.value=0;render()};slider.oninput=render;render();
</script></body></html>'''
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(template.replace('__JSON_DATA__',payload),encoding='utf-8')
    return path

if __name__=='__main__':print(generate())
